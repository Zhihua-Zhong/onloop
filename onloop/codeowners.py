"""CODEOWNERS, generated from the policy and never edited by hand.

GitHub applies the last matching line, so lines run from the general path to the specific one. A path reserved to
the human is owned by the human's account; any other path is owned by the handle its role declares in
`roles.<name>.codeowner` (a role with no handle writes no line: the path has no required code owner).
"""
from __future__ import annotations

import difflib

from .policy import Policy, normalise

HEADER = ("# Generated by onloop from onloop.yaml. Do not edit by hand: change the policy, then run\n"
          "#   onloop codeowners --write\n")


def _pattern(key: str) -> str:
    k = normalise(key)
    return "/" + k if not k.startswith("/") else k


def handle_for(policy: Policy, key: str) -> str | None:
    rule = policy.paths[key]
    if rule.reserved and policy.approver_of(rule.reserved) == "human":
        return "@" + policy.human
    if rule.owner:
        handle = policy.roles.get(rule.owner, {}).get("codeowner")
        return handle or None
    return None


def generate(policy: Policy) -> str:
    lines = [HEADER]
    for key in sorted(policy.paths, key=lambda k: (len(normalise(k)), normalise(k))):
        handle = handle_for(policy, key)
        if handle:
            lines.append(f"{_pattern(key)} {handle}\n")
    return "".join(lines)


def check(policy: Policy, existing: str | None) -> list[str]:
    """Differences between the committed CODEOWNERS and what the policy generates. Empty means they agree."""
    want = generate(policy)
    if existing is None:
        return ["CODEOWNERS does not exist; run `onloop codeowners --write`"]
    if existing == want:
        return []
    diff = difflib.unified_diff(existing.splitlines(), want.splitlines(), "CODEOWNERS (committed)",
                                "CODEOWNERS (generated)", lineterm="", n=1)
    return ["CODEOWNERS differs from the policy:"] + list(diff)


def self_test() -> tuple[bool, list[str]]:
    """The check must fail when the file drifts, and pass when it matches."""
    from .policy import from_dict
    p = from_dict({
        "human": "owner-a", "reviewer": "rev-bot", "agents": "agent-bot",
        "roles": {"builder": {"codeowner": "@org/builders"}},
        "paths": {"src/": {"owner": "builder"}, "onloop.yaml": {"reserved": "authority_widening"}},
    })
    good = generate(p)
    lines, ok = [], True
    for label, text, want_clean in (("matches", good, True), ("drifted", good + "/src/x @someone\n", False),
                                    ("missing", None, False)):
        clean = not check(p, text)
        right = clean == want_clean
        ok &= right
        lines.append(f"  {'ok' if right else 'FAILED'} codeowners check, file {label}")
    return ok, lines
